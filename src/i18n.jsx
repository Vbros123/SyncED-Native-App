const messages = Object.fromEntries(
  Object.entries(baseMessages).map(([language, values]) => [language, { ...values, ...(extendedMessages[language] || {}) }]),
)

const I18nContext = createContext(null)

function interpolate(value, variables) {
  return Object.entries(variables || {}).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
    value,
  )
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem('synced-language') || 'en')

  const setLanguage = (next) => {
    if (!languages.some((item) => item.id === next)) return
    localStorage.setItem('synced-language', next)
    setLanguageState(next)
  }

  const value = useMemo(() => {
    const locale = languages.find((item) => item.id === language) || languages[0]
    const t = (source, variables) => {
      const translated = messages[language]?.[source]
      if (language !== 'en' && translated === undefined && typeof window !== 'undefined' && window.__SYNCED_I18N_AUDIT__) {
        window.__SYNCED_I18N_MISSES__ ||= {}
        window.__SYNCED_I18N_MISSES__[language] ||= []
        if (!window.__SYNCED_I18N_MISSES__[language].includes(source)) window.__SYNCED_I18N_MISSES__[language].push(source)
      }
      return interpolate(translated || source, variables)
    }
    const formatDate = (date, options = { month: 'short', day: 'numeric' }) => new Intl.DateTimeFormat(language, options).format(date)
    return { language, setLanguage, locale, t, formatDate }
  }, [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used within I18nProvider')
  return value
}

